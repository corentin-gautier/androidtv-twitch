"""Draws the launcher icon (vector drawable) and the TV banner (PNG) from Twitch's logo, made to wink.

Usage, from the repository root: python3 scripts/make-icon.py [preview.png]
Rewrites ic_launcher_foreground.xml and banner.png; with a path, also saves a preview of both.
Needs Pillow (pip install pillow).

The logo and the purple are Twitch's trademarks: fine on a personal device, not for distribution.
"""
import os
import re
import sys
from PIL import Image, ImageChops, ImageDraw, ImageFont

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
out = sys.argv[1] if len(sys.argv) > 1 else None
PURPLE, WHITE = "#9146FF", "#FFFFFF"

# Twitch's "Glitch" logo on a 24x24 grid, as published by the Simple Icons project. Straight lines
# only, filled with the even-odd rule: the outline of the bubble, and the two bars that are its eyes.
# One change tells this app from the official one in a launcher: the right eye is laid flat, as a wink
# (in the original it is "M16.286 4.714H18v5.143h-1.714z", upright like the left one).
GLITCH = ("M11.571 4.714h1.715v5.143H11.57zM15.343 6.428h3.6v1.715h-3.6zM6 0L1.714 4.286v15.428h5.143V24l4.286-4.286h3.428"
          "L22.286 12V0zm14.571 11.143l-3.428 3.428h-3.429l-3 3v-3H6.857V1.714h13.714Z")
GLITCH_SIZE = 24

# In the 108x108 adaptive-icon grid, launchers show the middle 72 as a circle: the logo takes half of it.
ICON_SCALE = 1.5
ICON_OFFSET = (108 - GLITCH_SIZE * ICON_SCALE) / 2

xml = f'''<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <!-- Twitch's Glitch logo, winking. Generated by scripts/make-icon.py. -->
    <group
        android:scaleX="{ICON_SCALE}"
        android:scaleY="{ICON_SCALE}"
        android:translateX="{ICON_OFFSET}"
        android:translateY="{ICON_OFFSET}">
        <path
            android:fillColor="{WHITE}"
            android:fillType="evenOdd"
            android:pathData="{GLITCH}" />
    </group>
</vector>
'''
open(f"{root}/app/src/main/res/drawable/ic_launcher_foreground.xml", "w").write(xml)


def polygons(path):
    """The closed outlines of an SVG path made of M, L, H, V and Z commands, absolute or relative."""
    result, points, x, y = [], [], 0.0, 0.0
    for command, arguments in re.findall(r"([MLHVZmlhvz])([^MLHVZmlhvz]*)", path):
        numbers = [float(n) for n in re.findall(r"-?\d*\.?\d+", arguments)]
        relative = command.islower()
        kind = command.upper()
        if kind == "Z":
            result.append(points)
            x, y = points[0]
            points = []
        elif kind == "H":
            for n in numbers:
                x = x + n if relative else n
                points.append((x, y))
        elif kind == "V":
            for n in numbers:
                y = y + n if relative else n
                points.append((x, y))
        else:  # M or L, with pairs of coordinates
            for dx, dy in zip(numbers[::2], numbers[1::2]):
                x, y = (x + dx, y + dy) if relative else (dx, dy)
                points.append((x, y))
    return result


def glitch(image, scale, ox, oy, color):
    """Paints the logo on [image], its 24-unit grid scaled by [scale] and moved by (ox, oy)."""
    mask = Image.new("1", image.size, 0)
    for outline in polygons(GLITCH):
        layer = Image.new("1", image.size, 0)
        ImageDraw.Draw(layer).polygon([(ox + x * scale, oy + y * scale) for x, y in outline], fill=1)
        mask = ImageChops.logical_xor(mask, layer)  # the even-odd rule
    image.paste(color, mask=mask)


SS = 4  # supersampling, for smooth edges

# Banner, 320x180: the logo, then the name.
W, H = 320 * SS, 180 * SS
banner = Image.new("RGB", (W, H), PURPLE)
d = ImageDraw.Draw(banner)
font = ImageFont.truetype(f"{root}/app/src/main/res/font/space_grotesk.ttf", 32 * SS)
font.set_variation_by_axes([700])
name = "Twitch Lite"
scale = 2.6 * SS
logo, gap = GLITCH_SIZE * scale, 16 * SS
x = (W - (logo + gap + d.textlength(name, font=font))) / 2
glitch(banner, scale, x, (H - logo) / 2, WHITE)
d.text((x + logo + gap, H / 2), name, font=font, fill=WHITE, anchor="lm")
banner.resize((320, 180), Image.LANCZOS).save(f"{root}/app/src/main/res/drawable-xhdpi/banner.png")

# Preview: the icon as a launcher circle, at two sizes, beside the banner.
if out is None:
    sys.exit()
size = 432 * SS
icon = Image.new("RGB", (size, size), PURPLE)
glitch(icon, ICON_SCALE * size / 108, ICON_OFFSET * size / 108, ICON_OFFSET * size / 108, WHITE)
visible = icon.crop((size // 6, size // 6, size * 5 // 6, size * 5 // 6)).resize((288, 288), Image.LANCZOS)
mask = Image.new("L", (288 * SS, 288 * SS), 0)
ImageDraw.Draw(mask).ellipse([0, 0, 288 * SS, 288 * SS], fill=255)
mask = mask.resize((288, 288), Image.LANCZOS)
preview = Image.new("RGB", (860, 340), "#05060A")
preview.paste(visible, (26, 26), mask)
small = visible.resize((96, 96), Image.LANCZOS)
preview.paste(small, (350, 122), mask.resize((96, 96), Image.LANCZOS))
preview.paste(Image.open(f"{root}/app/src/main/res/drawable-xhdpi/banner.png"), (490, 80))
preview.save(out)
